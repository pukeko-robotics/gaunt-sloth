/**
 * EXT-112 — the §8 pattern surface, frozen, so a NARROWING of the shell floor cannot land silently.
 *
 * ## What this gate is for (read this before treating a red cell as a defect)
 *
 * It does not detect a bypass and it cannot. **It forces a DECLARATION.** A red cell here is the
 * moment the editor has to say what their edit removed, and the only way to green it is to edit the
 * literal below — a source change that shows up in the diff and has to be defended in review.
 *
 * The reason a declaration is needed at all is that nothing else in the repo can review a narrowing.
 * If an edit had removed a refusal that any spec asserts, that spec would be red — so a narrowing
 * that leaves the suite green has, by construction, a removal set that is entirely unasserted, which
 * is the same set as "uncovered". Green is structurally silent here, and an AI review of the diff is
 * no better: both read what the change still does, and the whole risk is in what it quietly stopped
 * doing. `hardline.ts`'s "How it may SHRINK" paragraph is the rule; this is its enforcement.
 *
 * ## Why an in-source literal and not `toMatchSnapshot()`
 *
 * A `.snap` file is regenerated by `vitest -u`. A gate whose entire purpose is to force a deliberate
 * declaration must not be satisfiable by a flag, so the expected surface is written out here as
 * ordinary source.
 *
 * ## What the gate provably CANNOT see
 *
 * It freezes strings. Floor behaviour is not only strings, so these narrowings move nothing here:
 *
 *  - **`normalizeCommand` is a FUNCTION** applied to the command before any pattern is tried. A
 *    narrowing implemented inside normalisation — dropping the fullwidth fold, or the backslash
 *    collapse — changes what the floor refuses without touching one frozen character.
 *  - **Control flow**: `isDeterministicExfiltration`'s per-pipeline split and its source-AND-sink
 *    conjunction, and the order `checkHardline` tries the arms. Dropping one of the two sink tests
 *    is a total narrowing of that arm and moves no string.
 *  - **A pattern built inside a function body.** The completeness check below enumerates what
 *    `hardline.ts` binds at MODULE SCOPE; a regex constructed inside a function is not a binding it
 *    can see. What that check does now cover is every module-scope binding regardless of the FORM it
 *    is declared in — it walks the TypeScript AST rather than scanning lines, so a continuation
 *    declarator, an `enum`, or a destructuring pattern is enumerated like any other.
 *
 * Said plainly rather than left to a green run to overclaim: this gate covers the pattern surface,
 * not the floor.
 */

